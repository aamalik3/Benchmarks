void Frame_Template(u32 LOC, u32 OFFSET ,bool print_on)
{
	int index=0;
	if(print_on == true){
	xil_printf("\n** Uploading Frame @:%08x ** ", (LOC+OFFSET));
	}

	for(int DRAM_Addr=0; DRAM_Addr <=(HEADER_FRAME_DUMMY_FOOTER)<<2; DRAM_Addr=DRAM_Addr+4)
	{
		Xil_Out32((LOC + DRAM_Addr+ OFFSET), Frame[index]);
		index++;
		usleep(1000);
	}
	if(print_on == true){
	xil_printf("-- ** Upload  Finished ***");
	}
//	xil_printf(".");

}
